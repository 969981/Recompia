"""The game's module list as a C++ header, for the code that links the lifted modules (a game's boot code and its exe stub).

The list is the game config's module table (ModuleSpec), written once here for every consumer: CMake runs
`python -m nxrecomp module-header` at configure time, the player build calls write() directly. The header holds one
X-macro, in load order (the entry module first, then the others in NxModule.index order):

    #define NX_MODULES(M) \
        M(rtld, "rtld", 0x7700000000ull) \
        ...

M(name, file, base): `name` is the identifier (the lifted libraries define `nxmod_<name>` and `nxmod_<name>_abi`), `file` the
module's file name in the ExeFS, `base` its guest address.
"""
import os


def load_order(modules):
    """The modules in the order the console maps them: the entry module first, the others by NxModule.index."""
    entry = [m for m in modules if m.entry]
    if len(entry) != 1:
        raise ValueError('exactly one module must be the entry module, found %d' % len(entry))
    return entry + [m for m in modules if not m.entry]


def render(modules):
    """The text of the header for a list of ModuleSpec."""
    rows = ['    M(%s, "%s", 0x%xull)' % (m.name, m.source or m.name, m.base) for m in load_order(modules)]
    return ('// Generated by nxrecomp (modheader.py) from the game config: do not edit.\n#pragma once\n'
            '#define NX_MODULES(M) \\\n' + ' \\\n'.join(rows) + '\n')


def write(modules, path):
    """Write the header to path unless it already holds exactly this text (so a configure does not recompile its users)."""
    text = render(modules)
    try:
        with open(path, encoding='utf-8', newline='') as f:
            if f.read() == text:
                return
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(text)
