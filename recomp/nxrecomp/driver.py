"""The program level of the lifter (driver): function discovery -> one C++ function per guest function -> sharded sources.

Adapted from smo-recomp tools/lifter/recomp.py (GPL-3.0-or-later: Env, lift_function, cmd_full2, cmd_cover), with:
  * an `Image` (image.py) in place of module globals, so several modules lift in one process and tests lift ELFs;
  * a per-game `GameConfig` (config.py) in place of SMO-specific rules;
  * C++ landing-pad resume entries (`u_<entry>(c, rp)`), after ssbu-recomp tools/lifter/recomp_eh.py (GPL-3.0-or-later);
  * jump tables resolved to bounded switches (jumptables.py, after SuperMarioWonderRecomp's resolver, MIT);
  * output sharded into a fixed number of translation units (for CMake) or by guest address (for stable files);
  * a module descriptor `nxmod_<name>` (ctx.h: NxModule) instead of smo's loose tables.

Generated files, in <outdir>:
    c_<NNN>.cpp   the lifted functions (shards)        funcs.h     declarations of every f_<addr> / u_<addr>
    module_<name>.cpp   function table, dynamic symbols, resume table, unwind tables  (the NxModule)

Split by job: sites.py (site lists, patches), env.py (per-module state), emit_function.py (one guest function -> C++),
module_emit.py (funcs.h, module_<name>.cpp), outfiles.py, cover.py (coverage). This module: discovery, shard planning and the worker pool.
"""
import bisect
import collections
import multiprocessing
import os
import time

from .image import Image
from . import locals as localsmod
from . import spin as spinmod
from .env import Env
from .sites import load_patches, load_sites
from .emit_function import lift_function
from .module_emit import write_module_files
from .outfiles import write_if_changed

GEN_HEADER = '/* generated by nxrecomp -- do not edit */\n#include <nxrecomp/cxx.h>\n#include "funcs.h"\n\n'


def make_env(spec):
    """Rebuild an Env in a worker from a picklable spec."""
    img = open_image(spec)
    from .config import load_game
    cfg = load_game(spec.get('game'))
    env = Env(img, cfg)
    env.module_index = module_index_of(cfg, spec)
    if spec.get('patches'):
        env.patches = load_patches(spec['patches'], img)
    if spec.get('sites'):
        load_sites(spec['sites'], env)
    env.ends = dict(spec['ends'])
    env.starts = sorted(env.ends)
    env.jt = {int(k): v for k, v in spec['jt'].items()}
    env.tailbr = set(spec.get('tailbr', ()))
    env.pads = spec['pads']
    env.catchers = set(spec['catchers'])
    env.full = True
    env.spin = True
    env.spin_yield = bool(spec.get('spin_yield') or cfg.spin_yield)
    env.locals = locals_mode(cfg, spec)
    env.flags_table = spec.get('flags_table')
    return env


def locals_mode(cfg, spec):
    """How the lifted functions keep registers and flags (locals.py): None (in the Ctx), 'exact', 'aapcs' or 'lean'."""
    from .config import reg_locals_mode
    mode = reg_locals_mode(cfg, spec.get('locals'))
    return None if mode == 'off' else mode


def module_index_of(cfg, spec):
    """NxModule.index: --index, else the position of the module in the game config's list, else 0."""
    if spec.get('index') is not None:
        return int(spec['index'])
    for i, m in enumerate(cfg.modules):
        if m.name == spec.get('name'):
            return i
    return 0


def open_image(spec):
    k = spec['kind']
    if k == 'nso':
        return Image.from_nso(open(spec['path'], 'rb').read(), spec['base'], spec['name'])
    if k == 'nx_elf':
        return Image.from_nx_elf(spec['path'], spec['base'], spec['name'])
    return Image.from_static_elf(spec['path'], spec['name'])


_worker_env = None


def _worker_init(spec):
    global _worker_env
    _worker_env = make_env(spec)


def _worker_scan(entries):
    """entries: [(entry, end or None)]; an end given here replaces the one the worker's spec has (discovery shortens them)."""
    env = _worker_env
    env.wanted = collections.OrderedDict()
    total = bad = 0
    keep, env.spin = env.spin, False                 # discovery needs only the branch targets
    keep_locals, env.locals = env.locals, None
    for a, end in entries:
        if end is not None:
            env.ends[a] = end
        _, n, b, _ = lift_function(env, a)
        total += n
        bad += len(b)
    env.spin, env.locals = keep, keep_locals
    return total, bad, list(env.wanted)


def _worker_summary(entries):
    """'lean' summary pass: {entry: locals.summarize()} of the given functions (their text is not kept)."""
    env = _worker_env
    env.wanted = collections.OrderedDict()
    env.locals_summaries = {}
    for a in entries:
        t = lift_function(env, a)[0]
        if a not in env.locals_summaries:                  # a PLT stub: lift_function returned before the locals pass
            s = localsmod.stub_summary(t)
            if s:
                env.locals_summaries[a] = s
    return env.locals_summaries


def entered_from_outside(env, cfg, img, funcs, sums):
    """('lean') (external, entered). external: the functions whose caller outside the module may read the flags they
    leave: the entry point (its caller is the host) and the exported symbols (another module's lift does not see what
    its callers read). entered: every function code outside the direct calls may enter: those, the game config's extra
    entries, and every function whose address the module may hold: a function entry stored as a 64-bit word anywhere
    outside .text (absolute, or module-relative as an NSO's unrelocated pointers and RELATIVE addends are), a literal of a lifted
    function's text (adr, a return address, ...), or in a 4 KiB page that a page-aligned literal (adrp) names."""
    import array
    fs = set(funcs)
    entry = {env.text_lo if img.meta.get('entry') is None else img.meta['entry']}
    out = {env.base + off for off in cfg.extra_entries.get(img.name, ())} & fs
    if img.symtab_is_dynamic:
        for _, typ, _, shndx, value, _ in img.symbols():
            if shndx and typ != 6 and shndx != 0xfff1:
                entry.add(img.base + img.sym_value(value))
    entry &= fs
    out |= entry
    lo, hi = img.text[0], img.text[0] + img.text[1]
    mem = bytes(img.mem)
    for a, b in ((0, lo), (hi, len(mem))):
        a += -a % 8
        words = array.array('Q')
        words.frombytes(mem[a:a + (b - a) // 8 * 8])
        w = set(words)
        out |= w & fs
        out |= {f for f in fs if f - env.base in w}
    out |= {env.base + addend for _, _, addend in img.relocs() if env.base + addend in fs}
    order = sorted(fs)
    for s in sums.values():
        if s == localsmod.IMPORT:
            continue
        for lit in s[5]:
            if lit in fs:
                out.add(lit)
            if lit % 4096 == 0 and env.text_lo <= lit < env.text_hi:
                k = bisect.bisect_left(order, lit)
                while k < len(order) and order[k] < lit + 4096:
                    out.add(order[k])
                    k += 1
    return entry, out & fs


def flag_table(pool, env, cfg, img, groups, all_funcs, log):
    """'lean': the summary pass over every function and locals.solve() -> the flag table the text pass consults."""
    sums = {}
    for part in map_ordered(pool, _worker_summary, groups):
        sums.update(part)
    entry, entered = entered_from_outside(env, cfg, img, all_funcs, sums)
    table, (bad_in, demands) = localsmod.solve(sums, entry, entered)
    log('%s: lean flag table over %d functions (%d imports): entry flags read %d, flags read after them %d, never leaving their entry flags %d; '
        'entered from '
        'outside the direct calls %d, of them reading their entry flags %d%s; demands on code entered from outside %d%s'
        % (img.name, len(sums), sum(1 for v in sums.values() if v == localsmod.IMPORT),
           sum(1 for v in table.values() if v[0]), sum(1 for v in table.values() if v[1]),
           sum(1 for v in table.values() if v[2]), len(entered), len(bad_in),
           ' (flags stored in front of every call_indirect)' if bad_in else '', len(demands),
           ' (every function entered from outside stores its flags at returns)' if demands else ''))
    if bad_in:
        log('  entered from outside, reading entry flags: ' + ' '.join('%x' % f for f in bad_in[:40]))
    if demands:
        log('  demands: ' + ' '.join('%x(%s)' % d for d in demands[:40]))
    return table


def _worker_text(entries):
    env = _worker_env
    env.wanted = collections.OrderedDict()
    texts, resume, insns = [], [], 0
    env.spin_stats = spinmod.Stats()
    env.locals_stats = localsmod.Stats()
    for a in entries:
        t, n, _, r = lift_function(env, a)
        texts.append(t)
        resume += r
        insns += n
    return '\n\n'.join(texts), resume, insns, env.spin_stats, env.locals_stats


def lift_module(spec, outdir, jobs=8, shards=0, bucket=0xC000, log=print):
    """Lift every function of the module described by `spec` into outdir.
    spec: dict(kind, path, base, name, game, patches). shards > 0: exactly that many c_NNN.cpp files (balanced by
    instruction count, contiguous in address order); shards == 0: one c_<bucket>.cpp per `bucket` bytes of guest code."""
    from .config import load_game
    t0 = time.time()
    img = open_image(spec)
    cfg = load_game(spec.get('game'))
    env = Env(img, cfg)
    env.module_index = module_index_of(cfg, spec)
    if spec.get('patches'):
        env.patches = load_patches(spec['patches'], img)
    if spec.get('sites'):
        load_sites(spec['sites'], env)
    env.compute_starts()
    for a in sorted(env.sites['midhook']):                 # a mid-function hook makes its address a function of its own
        if a not in env.ends:
            env.ends[a] = env.extent(a)
    env.starts = sorted(env.ends)
    env.load_eh()
    from . import jumptables
    jumptables.resolve(env)
    starts = env.starts
    log('%s: %d function entries, %d landing pads, %d jump tables  (%.1fs)' % (img.name, len(starts), len(env.pads), len(env.jt), time.time() - t0))
    spec = dict(spec, ends=env.ends, jt={str(k): v for k, v in env.jt.items()}, tailbr=sorted(env.tailbr), pads=env.pads, catchers=sorted(env.catchers))
    os.makedirs(outdir, exist_ok=True)
    known = set(starts)
    pending = list(starts)
    all_funcs, total, bad = [], 0, 0
    pool = multiprocessing.Pool(jobs, _worker_init, (spec,)) if jobs > 1 else None
    if pool is None:
        _worker_init(spec)
    try:
        mapper = pool.imap_unordered if pool else map
        # discovery: lifting finds branch targets that are not listed functions (tail calls, fall-through ends).
        # A found entry has no exact end (no FDE covers it): it ends at the next known entry and falls through into it. Each round can
        # find entries inside earlier found ones (code without unwind tables); those shrink and are scanned again, so no stretch of
        # code is lifted into more than one function.
        found, listed = set(), set()
        while pending:
            pending.sort()
            parts = [[(a, env.ends.get(a) if a in found else None) for a in pending[i:i + 400]] for i in range(0, len(pending), 400)]
            new = set()
            for n, b, wanted in mapper(_worker_scan, parts):
                total += n
                bad += b
                new.update(w for w in wanted if w not in known and env.text_lo <= w < env.text_hi)
            all_funcs += [a for a in pending if a not in listed]
            listed.update(pending)
            log('discovery: %d functions, %d extra branch targets  (%.1fs)' % (len(pending), len(new), time.time() - t0))
            known |= new
            found |= {w for w in new if w not in env.ends}
            order = sorted(known)
            again = []
            for a in found:
                i = bisect.bisect_right(order, a)
                end = order[i] if i < len(order) else env.text_hi
                if env.ends.get(a) != end:
                    if a in env.ends and a not in new:
                        again.append(a)
                    env.ends[a] = end
            pending = sorted(new | set(again))
        all_funcs.sort()
        # workers must know the new entries too (their extents are by the next start): rebuild the spec
        if len(all_funcs) != len(starts):
            spec['ends'] = {a: env.ends.get(a, env.extent(a)) for a in all_funcs}
            if pool:
                pool.close()
                pool = multiprocessing.Pool(jobs, _worker_init, (spec,))
                mapper = pool.imap_unordered
            else:
                _worker_init(spec)
        if locals_mode(cfg, spec) == localsmod.LEAN:     # the flag table, before any function is rewritten
            parts = [all_funcs[i:i + 400] for i in range(0, len(all_funcs), 400)]
            spec['flags_table'] = flag_table(pool, env, cfg, img, parts, all_funcs, log)
            if pool:
                pool.close()
                pool = multiprocessing.Pool(jobs, _worker_init, (spec,))
                mapper = pool.imap_unordered
            else:
                _worker_init(spec)
            # the table next to the sources (ind_in, ind_out, then entry NEEDS_IN NEEDS_OUT KILLS), for checks of the generated code
            ft = spec['flags_table']
            write_if_changed(os.path.join(outdir, 'flags_%s.txt' % img.name),
                             'ind_in %d ind_out %d\n' % (ft.ind_in, ft.ind_out)
                             + ''.join('%x %d %d %d\n' % (a, i, o, k) for a, (i, o, k) in sorted(ft.items())))
        # shard assignment
        sizes = {a: max(1, (spec['ends'][a] - a) // 4) for a in all_funcs}
        groups = collections.OrderedDict()
        if shards:
            target = sum(sizes.values()) / float(shards)
            k, acc = 0, 0
            for a in all_funcs:
                if acc >= target and k < shards - 1:
                    k, acc = k + 1, 0
                groups.setdefault(k, []).append(a)
                acc += sizes[a]
            names = {k: 'c_%03d.cpp' % k for k in range(shards)}
            for k in range(shards):
                groups.setdefault(k, [])
        else:
            for a in all_funcs:
                groups.setdefault((a - env.base) // bucket, []).append(a)
            names = {k: 'c_%04x.cpp' % k for k in groups}
        jobs_list = [(k, v) for k, v in groups.items()]
        resume, files, changed, insns = [], [], 0, 0
        sst, lst = spinmod.Stats(), localsmod.Stats()
        for (k, entries), (text, res, n, ss, ls) in zip(jobs_list, map_ordered(pool, _worker_text, [v for _, v in jobs_list])):
            resume += res
            insns += n
            sst.add(ss)
            lst.add(ls)
            content = GEN_HEADER + text + '\n'
            files.append(names[k])
            changed += write_if_changed(os.path.join(outdir, names[k]), content)
    finally:
        if pool:
            pool.close()
    first = {}
    for lp, e in sorted(resume):
        first.setdefault(lp, e)
    resume = sorted(first.items())
    catchers = sorted(a for a in env.catchers if a in set(all_funcs))
    write_module_files(env, outdir, all_funcs, resume, catchers)
    keep = set(files) | {'funcs.h', 'module_%s.cpp' % img.name}
    for n in os.listdir(outdir):
        if (n.endswith('.cpp') and n.startswith('c_')) and n not in keep:
            os.remove(os.path.join(outdir, n))
    log('%s: functions %d   files %d (%d rewritten)   instructions %d   not translated %d   (%.1fs)'
        % (img.name, len(all_funcs), len(files), changed, insns, bad, time.time() - t0))
    log(sst.line(img.name))
    if sst.unprotected:
        log('  spin-loop loads left plain (no rd*/ld<> in their text): ' + ' '.join('%x' % a for a in sorted(sst.unprotected)[:40]))
    mode = locals_mode(cfg, spec)
    if mode:
        for line in lst.lines(img.name, mode):
            log(line)
    return {'functions': len(all_funcs), 'files': files, 'instructions': insns, 'not_translated': bad, 'spin_loops': sst.loops}


def map_ordered(pool, fn, items):
    return pool.map(fn, items) if pool else [fn(i) for i in items]
