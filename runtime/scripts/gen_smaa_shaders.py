# Compiles the SMAA 1x passes (edge detection, blend weights, neighbourhood blend) with glslc, validates them with spirv-val and writes
# src/gfx/extras/smaa_shaders.inc (uint32 arrays). The .inc is committed, so building the runtime does not need the SDK.
# Run: python -I scripts/gen_smaa_shaders.py   (exit 1 and no .inc written if a shader fails to compile or validate)
# glslc / spirv-val: the GLSLC and SPIRV_VAL environment variables, else the Vulkan SDK's, else the ones on PATH.
#
# SMAA (MIT, third_party/smaa, unmodified) is compiled as GLSL (SMAA_GLSL_4). The pass sees the game's scene-linear HDR colour (the input of the
# tone map): a temporary copy of SMAA.hlsl sends its edge-detection fetches through smaa_edge_in(), which compresses c to sqrt(c / (1 + c)) so the
# thresholds mean what they do on a display-referred picture. The blend pass reads the raw colour.
# Four quality levels, the SMAA presets Low, Medium, High and Ultra, all with luma edges. The layouts are written into the .inc header.
import os, re, shutil, struct, subprocess, sys, tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
smaa_dir = os.path.join(root, "third_party", "smaa")
out_path = os.path.join(root, "src", "gfx", "extras", "smaa_shaders.inc")


def tool(env, sdk_name):
    if os.environ.get(env):
        return os.environ[env]
    sdk = os.path.join(r"C:\VulkanSDK\1.4.363.0\Bin", sdk_name + ".exe")
    if os.path.exists(sdk):
        return sdk
    found = shutil.which(sdk_name)
    if not found:
        sys.stderr.write("%s not found (set %s)\n" % (sdk_name, env))
        sys.exit(1)
    return found


glslc = tool("GLSLC", "glslc")
spirv_val = tool("SPIRV_VAL", "spirv-val")

PRE = """#version 450
#extension GL_GOOGLE_include_directive : enable
#define SMAA_GLSL_4 1
#define @PRESET@ 1
#define SMAA_INCLUDE_VS @VS@
#define SMAA_INCLUDE_PS @PS@
layout(push_constant) uniform PushConstants { vec4 metrics; } pc;   // 1/w, 1/h, w, h of the scene image
#define SMAA_RT_METRICS pc.metrics

vec4 smaa_edge_in(sampler2D t, vec2 uv) {
    vec3 c = max(texture(t, uv).rgb, vec3(0.0));
    return vec4(sqrt(c / (vec3(1.0) + c)), 1.0);
}
#include "SMAA.hlsl"
"""

EDGE_VS = """
layout(location = 0) out vec2 v_uv;
layout(location = 1) out vec4 v_off[3];
void main() {
    vec2 p = vec2(float((gl_VertexIndex << 1) & 2), float(gl_VertexIndex & 2));
    v_uv = p;
    gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);
    SMAAEdgeDetectionVS(v_uv, v_off);
}
"""
EDGE_FS = """
layout(set = 0, binding = 0) uniform sampler2D u_color;
layout(location = 0) in vec2 v_uv;
layout(location = 1) in vec4 v_off[3];
layout(location = 0) out vec4 o;
void main() {
    vec2 e = @EDGE@(v_uv, v_off, u_color);
    o = vec4(e, 0.0, 0.0);
}
"""
WEIGHT_VS = """
layout(location = 0) out vec2 v_uv;
layout(location = 1) out vec2 v_pix;
layout(location = 2) out vec4 v_off[3];
void main() {
    vec2 p = vec2(float((gl_VertexIndex << 1) & 2), float(gl_VertexIndex & 2));
    v_uv = p;
    gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);
    SMAABlendingWeightCalculationVS(v_uv, v_pix, v_off);
}
"""
WEIGHT_FS = """
layout(set = 0, binding = 0) uniform sampler2D u_edges;
layout(set = 0, binding = 1) uniform sampler2D u_area;
layout(set = 0, binding = 2) uniform sampler2D u_search;
layout(location = 0) in vec2 v_uv;
layout(location = 1) in vec2 v_pix;
layout(location = 2) in vec4 v_off[3];
layout(location = 0) out vec4 o;
void main() {
    o = SMAABlendingWeightCalculationPS(v_uv, v_pix, v_off, u_edges, u_area, u_search, vec4(0.0));
}
"""
BLEND_VS = """
layout(location = 0) out vec2 v_uv;
layout(location = 1) out vec4 v_off;
void main() {
    vec2 p = vec2(float((gl_VertexIndex << 1) & 2), float(gl_VertexIndex & 2));
    v_uv = p;
    gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);
    SMAANeighborhoodBlendingVS(v_uv, v_off);
}
"""
BLEND_FS = """
layout(set = 0, binding = 0) uniform sampler2D u_color;
layout(set = 0, binding = 1) uniform sampler2D u_blend;
layout(location = 0) in vec2 v_uv;
layout(location = 1) in vec4 v_off;
layout(location = 0) out vec4 o;
void main() {
    o = SMAANeighborhoodBlendingPS(v_uv, v_off, u_color, u_blend);
}
"""

HEADER = """// SPDX-License-Identifier: GPL-3.0-or-later
// SPIR-V of the SMAA 1x passes (smaa_scene.cpp), generated by scripts/gen_smaa_shaders.py from third_party/smaa (SMAA, MIT). Do not edit.
// Every pass: full-screen triangle (no vertex input), push constant vec4 metrics (1/w, 1/h, w, h) in the vertex and fragment stages.
//   kSmaaEdgeVert / kSmaaWeightVert / kSmaaBlendVert   vertex shaders
//   kSmaaEdgeLow / Medium / High / Ultra               fragment, set 0 binding 0 = scene colour (RGBA16F, scene-linear); writes RG8 edges.
//                                                      The SMAA preset of the same name, luma edges
//   kSmaaWeightLow / Medium / High / Ultra             fragment, set 0: 0 edges, 1 area texture (RG8 160x560), 2 search texture (R8 64x16); writes RGBA8
//   kSmaaBlend                                         fragment, set 0: 0 scene colour, 1 blend weights; writes RGBA16F
"""


def pre(preset, vs, ps):
    return PRE.replace("@PRESET@", preset).replace("@VS@", str(vs)).replace("@PS@", str(ps))


SHADERS = [
    ("kSmaaEdgeVert", "vert", pre("SMAA_PRESET_HIGH", 1, 0) + EDGE_VS),
    ("kSmaaWeightVert", "vert", pre("SMAA_PRESET_HIGH", 1, 0) + WEIGHT_VS),
    ("kSmaaBlendVert", "vert", pre("SMAA_PRESET_HIGH", 1, 0) + BLEND_VS),
    ("kSmaaEdgeLow", "frag", pre("SMAA_PRESET_LOW", 0, 1) + EDGE_FS.replace("@EDGE@", "SMAALumaEdgeDetectionPS")),
    ("kSmaaEdgeMedium", "frag", pre("SMAA_PRESET_MEDIUM", 0, 1) + EDGE_FS.replace("@EDGE@", "SMAALumaEdgeDetectionPS")),
    ("kSmaaEdgeHigh", "frag", pre("SMAA_PRESET_HIGH", 0, 1) + EDGE_FS.replace("@EDGE@", "SMAALumaEdgeDetectionPS")),
    ("kSmaaEdgeUltra", "frag", pre("SMAA_PRESET_ULTRA", 0, 1) + EDGE_FS.replace("@EDGE@", "SMAALumaEdgeDetectionPS")),
    ("kSmaaWeightLow", "frag", pre("SMAA_PRESET_LOW", 0, 1) + WEIGHT_FS),
    ("kSmaaWeightMedium", "frag", pre("SMAA_PRESET_MEDIUM", 0, 1) + WEIGHT_FS),
    ("kSmaaWeightHigh", "frag", pre("SMAA_PRESET_HIGH", 0, 1) + WEIGHT_FS),
    ("kSmaaWeightUltra", "frag", pre("SMAA_PRESET_ULTRA", 0, 1) + WEIGHT_FS),
    ("kSmaaBlend", "frag", pre("SMAA_PRESET_HIGH", 0, 1) + BLEND_FS),
]


def hex_words(words, name):
    lines = ["static const uint32_t %s[] = {\n" % name]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
    lines.append("};\n")
    return "".join(lines)


def main():
    body = [HEADER]
    rows = []
    failed = False
    with tempfile.TemporaryDirectory() as tmp:
        # a copy of SMAA.hlsl whose colour edge fetches go through smaa_edge_in()
        text = open(os.path.join(smaa_dir, "SMAA.hlsl"), encoding="utf-8", errors="replace").read()
        text, n = re.subn(r"SMAASamplePoint\(colorTex,", "smaa_edge_in(colorTex,", text)
        if n != 14:
            sys.stderr.write("SMAA.hlsl: expected 14 colour edge fetches, found %d\n" % n)
            sys.exit(1)
        with open(os.path.join(tmp, "SMAA.hlsl"), "w", newline="\n", encoding="utf-8") as f:
            f.write(text)
        for cname, stage, src in SHADERS:
            path = os.path.join(tmp, cname + "." + stage)
            with open(path, "w", newline="\n") as f:
                f.write(src)
            res = subprocess.run([glslc, "-O", "--target-env=vulkan1.3", "-I", tmp, "-fshader-stage=" + stage, "-o", "-", path], capture_output=True)
            if res.returncode != 0:
                sys.stderr.write("glslc failed on %s:\n%s" % (cname, res.stderr.decode(errors="replace")))
                sys.exit(1)
            spv = res.stdout
            sp = os.path.join(tmp, cname + ".spv")
            with open(sp, "wb") as f:
                f.write(spv)
            v = subprocess.run([spirv_val, "--target-env", "vulkan1.3", sp], capture_output=True, text=True)
            ok = v.returncode == 0
            words = struct.unpack("<%dI" % (len(spv) // 4), spv)
            rows.append((cname, len(words), "PASS" if ok else "FAIL"))
            if not ok:
                failed = True
                sys.stderr.write("spirv-val failed on %s:\n%s\n" % (cname, (v.stdout + v.stderr).strip()))
            body.append("\n" + hex_words(words, cname))
    print("%-22s %8s  %s" % ("name", "words", "spirv-val"))
    for name, n, verdict in rows:
        print("%-22s %8d  %s" % (name, n, verdict))
    if failed:
        print("FAILED: smaa_shaders.inc not written")
        sys.exit(1)
    with open(out_path, "w", newline="\n") as f:
        f.write("".join(body))
    print("wrote %s" % out_path)


if __name__ == "__main__":
    main()
